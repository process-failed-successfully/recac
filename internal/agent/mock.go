package agent

import (
	"context"
	"fmt"
	"strings"
)

// MockAgent is a simple mock agent for testing and mock mode
// It returns predefined responses without making actual API calls
type MockAgent struct {
	responsePrefix string
	forcedResponse string
}

// NewMockAgent creates a new mock agent
func NewMockAgent() *MockAgent {
	return &MockAgent{
		responsePrefix: "Mock agent response",
	}
}

// SetResponse forces a specific response from the agent
func (m *MockAgent) SetResponse(response string) {
	m.forcedResponse = response
}

// Send implements the Agent interface
func (m *MockAgent) Send(ctx context.Context, prompt string) (string, error) {
	if m.forcedResponse != "" {
		return m.forcedResponse, nil
	}

	// 1. Ticket Generation (Prioritized)
	if strings.Contains(prompt, "Ticket Generation") || strings.Contains(prompt, "ticket generation") || strings.Contains(prompt, "TPM Agent") || strings.Contains(prompt, "Technical Program Manager") {
		// Detect specific scenario
		if strings.Contains(prompt, "critical instruction for ticket generation") {
			// Return valid JSON array for smoke tests
			return `[
  {
    "title": "ID:[PRIMES] Implement Prime Number Generator",
    "description": "Create a python script to generate prime numbers.",
    "type": "Task",
    "status": "To Do",
    "priority": "High"
  }
]`, nil
		}
		// Generic ticket generation
		return `[
  {
    "title": "ID:[TASK-1] Example Task",
    "description": "This is an example task generated by Mock Agent.",
    "type": "Task",
    "status": "To Do",
    "priority": "Medium"
  }
]`, nil
	}

	// 2. Initializer (Project Setup)
	if strings.Contains(prompt, "agent-bridge import") || strings.Contains(prompt, "Initializer") {
		return "```bash\n# Create features.json first to avoid import error\ncat <<EOF > features.json\n{\n  \"project_name\": \"Mock Project\",\n  \"features\": [\n    {\n      \"id\": \"req-initial-setup\",\n      \"description\": \"Initial setup\",\n      \"category\": \"core\",\n      \"priority\": \"critical\",\n      \"status\": \"pending\"\n    }\n  ]\n}\nEOF\n\ncat features.json | agent-bridge import\n```", nil
	}

	// 3. QA Agent
	if strings.Contains(prompt, "QA AGENT") {
		return "```bash\nagent-bridge signal set QA_PASSED true\n```", nil
	}

	// 4. Implementation Request (Prime Python)
	if strings.Contains(prompt, "calculate primes") || strings.Contains(prompt, "[PRIMES]") || (strings.Contains(prompt, "primes.py") && strings.Contains(prompt, "create")) {
		return fmt.Sprintf("Sure, I'll implement the prime number generator.\n\n```bash\ncat <<EOF > primes.py\ndef is_prime(n):\n    if n <= 1:\n        return False\n    for i in range(2, int(n**0.5) + 1):\n        if n %% i == 0:\n            return False\n    return True\n\nimport sys\nif __name__ == \"__main__\":\n    print(\"Primes up to 10:\")\n    for i in range(11):\n        if is_prime(i):\n            print(i)\nEOF\n```\n\n```bash\nagent-bridge feature set PRIMES --status done --passes true\n```"), nil
	}

	// 5. Generic / Default
	// Return a mock response that shows the agent received the prompt
	// This allows the session to run without requiring real API keys
	response := fmt.Sprintf("%s:\n\nI received your prompt (%d characters). In mock mode, I would process this request and provide a response. The actual implementation would call the AI provider API here.\n\nPrompt preview: %s...",
		m.responsePrefix, len(prompt), truncateString(prompt, 100))
	return response, nil
}

// SendStream implements the Agent interface
func (m *MockAgent) SendStream(ctx context.Context, prompt string, onChunk func(string)) (string, error) {
	resp, err := m.Send(ctx, prompt)
	if err == nil && onChunk != nil {
		onChunk(resp)
	}
	return resp, err
}

// truncateString truncates a string to a maximum length
func truncateString(s string, maxLen int) string {
	if len(s) <= maxLen {
		return s
	}
	return s[:maxLen]
}
