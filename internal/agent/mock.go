package agent

import (
	"context"
	"encoding/json"
	"fmt"
	"strings"
)

// MockAgent is a smart mock agent for testing and mock mode.
// It uses heuristics to return context-appropriate responses (JSON plans, Bash scripts, etc.)
// to support E2E tests without real AI calls.
type MockAgent struct {
	responsePrefix string
	forcedResponse string
}

// NewMockAgent creates a new mock agent
func NewMockAgent() *MockAgent {
	return &MockAgent{
		responsePrefix: "Mock agent response",
	}
}

// SetResponse forces a specific response from the agent
func (m *MockAgent) SetResponse(response string) {
	m.forcedResponse = response
}

// Send implements the Agent interface
func (m *MockAgent) Send(ctx context.Context, prompt string) (string, error) {
	if m.forcedResponse != "" {
		return m.forcedResponse, nil
	}

	// Heuristics for E2E scenarios

	// 1. TPM / Planning Phase (Jira Ticket Generation)
	// Prompt usually starts with "You are an expert Technical Program Manager (TPM)..."
	if strings.Contains(prompt, "Technical Program Manager") || strings.Contains(prompt, "agile software development") {
		// Check for specific scenario: Primes
		if strings.Contains(strings.ToLower(prompt), "prime") {
			// Return a JSON list of tickets as expected by the Jira generator
			tickets := []map[string]string{
				{
					"title":       "ID:[PRIMES] Implement Primes Calculation Script",
					"description": "Create a Python script to calculate primes up to 10,000.",
					"type":        "Task",
				},
			}
			jsonBytes, _ := json.Marshal(tickets)
			return string(jsonBytes), nil
		}
		// Generic plan
		tickets := []map[string]string{
			{
				"title":       "ID:[GENERIC] Generic Task",
				"description": "A generic task generated by MockAgent.",
				"type":        "Task",
			},
		}
		jsonBytes, _ := json.Marshal(tickets)
		return string(jsonBytes), nil
	}

	// 2. Coding Phase (Implementation)
	// Prompt usually includes "YOUR ROLE - CODING AGENT" or requests implementation
	if strings.Contains(prompt, "CODING AGENT") || (strings.Contains(prompt, "implement") && strings.Contains(prompt, "script")) {
		// Primes scenario
		if strings.Contains(strings.ToLower(prompt), "prime") {
			return `Here is the script to calculate primes.

` + "```bash" + `
cat << 'EOF' > primes.py
import json

def is_prime(n):
    if n <= 1:
        return False
    for i in range(2, int(n**0.5) + 1):
        if n % i == 0:
            return False
    return True

primes = [x for x in range(10000) if is_prime(x)]
print(json.dumps({"primes": primes}))
EOF
` + "```" + `
`, nil
		}
	}

	// 3. General Fallback
	response := fmt.Sprintf("%s:\n\nI received your prompt (%d characters). In mock mode, I would process this request and provide a response. The actual implementation would call the AI provider API here.\n\nPrompt preview: %s...",
		m.responsePrefix, len(prompt), truncateString(prompt, 100))
	return response, nil
}

// SendStream implements the Agent interface
func (m *MockAgent) SendStream(ctx context.Context, prompt string, onChunk func(string)) (string, error) {
	resp, err := m.Send(ctx, prompt)
	if err == nil && onChunk != nil {
		onChunk(resp)
	}
	return resp, err
}

// truncateString truncates a string to a maximum length
func truncateString(s string, maxLen int) string {
	if len(s) <= maxLen {
		return s
	}
	return s[:maxLen]
}
